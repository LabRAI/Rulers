# 4. Calibration & Metrics
# ==========================================

def run_calibration_pipeline(train_rows, test_rows, config):
    # 1. Prepare Data
    X_train = [r['raw_pred'] for r in train_rows if r['raw_pred'] != -1]
    y_train = [r['human'] for r in train_rows if r['raw_pred'] != -1]

    if len(X_train) < 5:
        print("Warning: Not enough valid calibration data.")
        iso = None
    else:
        # 2. Fit Isotonic
        iso = IsotonicRegression(y_min=config.min_score, y_max=config.max_score, out_of_bounds="clip")
        iso.fit(X_train, y_train)

    # 3. Predict & Round
    final_preds = []
    for r in test_rows:
        val = r['raw_pred']
        if val == -1:
            final_preds.append(config.min_score)
            continue

        # Apply Calibration
        if iso:
            val = iso.predict([val])[0]

        # Universal Rounding (Step Size)
        # e.g., 3.3 -> step 0.5 -> 3.3/0.5=6.6 -> 7 -> 7*0.5=3.5
        val = round(val / config.step_size) * config.step_size
        final_preds.append(val)

    return final_preds

