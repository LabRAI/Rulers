# 3. LLM Client & Scorer
# ==========================================

@dataclass
class UsageStats:
    prompt_tokens: int = 0
    completion_tokens: int = 0
    cost: float = 0.0
    lock: threading.Lock = field(default_factory=threading.Lock)

    def update(self, pt, ct):
        with self.lock:
            self.prompt_tokens += pt
            self.completion_tokens += ct
            # Approx cost (GPT-4o-mini)
            self.cost += (pt * 0.15 + ct * 0.60) / 1e6

def call_llm(model, messages, api_key, max_tokens=500):
    from openai import OpenAI
    client = OpenAI(api_key=api_key)
    try:
        resp = client.chat.completions.create(
            model=model, messages=messages, max_tokens=max_tokens, temperature=0.0,
            response_format={"type": "json_object"}
        )
        return resp.choices[0].message.content, resp.usage.prompt_tokens, resp.usage.completion_tokens
    except Exception as e:
        print(f"LLM Error: {e}")
        return "{}", 0, 0

def process_row_autoscore(row, config: TaskConfig, model: str, api_key: str, usage: UsageStats):
    """
    The Two-Stage Pipeline:
    1. Extraction: Get 'Z' (Evidence).
    2. Scoring: Get Score based on Z.
    """

    # --- Stage 1: Extraction ---
    sys_msg_1 = f"{config.sys_msg} Phase 1: Extraction."
    user_msg_1 = f"""
[Input Data]
{row['input_text'][:10000]}

[Rubric]
{config.rubric_text}

Task: Extract key evidence, strengths, and weaknesses relevant to the rubric.
Output strict JSON with keys: "evidence", "strengths", "weaknesses".
"""
    txt1, pt1, ct1 = call_llm(model, [{"role":"system","content":sys_msg_1}, {"role":"user","content":user_msg_1}], api_key, max_tokens=800)
    usage.update(pt1, ct1)

    # --- Stage 2: Scoring ---
    sys_msg_2 = f"{config.sys_msg} Phase 2: Scoring."
    user_msg_2 = f"""
[Rubric]
{config.rubric_text}

[Extracted Evidence]
{txt1}

[Original Input]
{row['input_text'][:4000]}

Task: Assign a score between {config.min_score} and {config.max_score}.
Output strict JSON: {{"score": <number>, "reason": "..."}}
"""
    txt2, pt2, ct2 = call_llm(model, [{"role":"system","content":sys_msg_2}, {"role":"user","content":user_msg_2}], api_key, max_tokens=300)
    usage.update(pt2, ct2)

    # --- Parsing ---
    try:
        data = json.loads(txt2)
        raw = float(data.get("score", -1))
    except:
        # Regex Fallback
        m = re.search(r'score":\s*([\d\.]+)', txt2)
        raw = float(m.group(1)) if m else -1.0

    # Clamp
    if raw != -1:
        raw = max(config.min_score, min(config.max_score, raw))

    return {
        "id": row['id'],
        "human": row['human_label'],
        "raw_pred": raw,
        "extraction": txt1,
        "reason": data.get("reason", "") if raw != -1 else ""
    }

