"""
Universal AutoScore Baseline
----------------------------
A fully generalized Two-Stage (Extraction -> Scoring) pipeline for any text evaluation task.

This script decouples the dataset specifics from the scoring logic.
It normalizes inputs into a standard schema and applies a configurable scoring pipeline.

Pipeline:
  1. Extraction Phase: LLM extracts rubric-relevant details (Evidence/Z).
  2. Scoring Phase: LLM assigns a score based on Evidence + Rubric.
  3. Calibration Phase: Isotonic Regression maps raw LLM scores to human distribution.

Usage:
  python run_autoscore_universal.py --preset ASAP --openai_key "..."
  python run_autoscore_universal.py --data_path data.csv --rubric_text "..." --min_score 1 --max_score 5
"""

