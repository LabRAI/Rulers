# 5. Main Execution
# ==========================================

def main():
    parser = argparse.ArgumentParser(description="Universal MTS (Evidence-First) Runner")

    # Input Data
    parser.add_argument("--data_path", required=True, help="Main data file")
    parser.add_argument("--test_path", help="Optional test file")
    parser.add_argument("--cols_text", default="text", help="Text column(s) to merge (comma-sep)")
    parser.add_argument("--col_label", default="label", help="Label column")
    parser.add_argument("--col_id", default="id", help="ID column")

    # MTS Configuration
    parser.add_argument("--traits", required=True, help="Comma-separated traits (e.g. 'Logic,Style')")
    parser.add_argument("--aggregator", choices=["MEAN", "SUM"], default="MEAN")

    # Target Scale
    parser.add_argument("--min_score", type=float, default=1)
    parser.add_argument("--max_score", type=float, default=6)
    parser.add_argument("--step_size", type=float, default=1.0)

    # Runtime
    parser.add_argument("--openai_key", default=os.getenv("OPENAI_API_KEY"))
    parser.add_argument("--model", default="gpt-4o-mini")
    parser.add_argument("--calib_n", type=int, default=100)
    parser.add_argument("--max_test", type=int, default=500)
    parser.add_argument("--parallel", type=int, default=8)
    parser.add_argument("--out_dir", default="results_mts_universal")

    args = parser.parse_args()

    # 1. Setup Config
    traits_list = [t.strip() for t in args.traits.split(",")]
    cols_text_list = [c.strip() for c in args.cols_text.split(",")]

    cfg = MTSConfig(
        traits=traits_list,
        aggregator=args.aggregator,
        min_score=args.min_score,
        max_score=args.max_score,
        step_size=args.step_size,
        cols_text=cols_text_list,
        col_label=args.col_label,
        col_id=args.col_id
    )

    print(f"--- Universal MTS (Evidence-First) ---")
    print(f"Traits: {cfg.traits}")
    print(f"Aggregator: {cfg.aggregator}")
    print(f"Target: [{cfg.min_score}, {cfg.max_score}] (Step {cfg.step_size})")

    # 2. Load Data
    full_df = smart_load(args.data_path)
    full_std = normalize_data(full_df, cfg)

    if args.test_path:
        test_raw = smart_load(args.test_path)
        test_std = normalize_data(test_raw, cfg)
        train_std = full_std
    else:
        train_std = full_std.iloc[:args.calib_n]
        test_std = full_std.iloc[args.calib_n:]

    train_std = train_std.head(args.calib_n)
    test_std = test_std.head(args.max_test)

    print(f"Train N: {len(train_std)} | Test N: {len(test_std)}")
    os.makedirs(args.out_dir, exist_ok=True)
    usage = UsageStats()

    # 3. Execution Helper
    def run_batch(df, desc):
        results = []
        with ThreadPoolExecutor(max_workers=args.parallel) as ex:
            futs = [ex.submit(score_row_evidence_first, row, cfg, args.model, args.openai_key, usage) for _, row in df.iterrows()]
            for f in as_completed(futs):
                results.append(f.result())
            print(f"Finished {desc}")
        return results

    # Run
    calib_res = run_batch(train_std, "Calibration")
    test_res = run_batch(test_std, "Testing")

    # 4. Calibration & Predict
    final_preds = run_calibration(calib_res, test_res, cfg)

    # 5. Metrics
    y_true = [r['human'] for r in test_res]

    # QWK Map
    factor = int(1 / cfg.step_size)
    yt_int = np.round(np.array(y_true) * factor).astype(int)
    yp_int = np.round(np.array(final_preds) * factor).astype(int)

    qwk = cohen_kappa_score(yt_int, yp_int, weights="quadratic")

    # Save
    out_df = pd.DataFrame(test_res)
    out_df['final_pred'] = final_preds
    out_df.to_csv(os.path.join(args.out_dir, "predictions.csv"), index=False)

    print("\n" + "="*40)
    print(f"MTS RESULTS")
    print(f"QWK Score: {qwk:.4f}")
    print(f"Est. Cost: ${usage.cost:.4f}")
    print("="*40)

if __name__ == "__main__":
    main()