def smart_load(path: str) -> pd.DataFrame:
    """Auto-detects format and loads DataFrame."""
    if path.endswith(".parquet"): return pd.read_parquet(path)
    if path.endswith(".tsv"): return pd.read_csv(path, sep='\t', encoding='latin1')
    try: return pd.read_csv(path, encoding='utf-8')
    except: return pd.read_csv(path, encoding='latin1')

def normalize_data(df: pd.DataFrame, config: TaskConfig) -> pd.DataFrame:
    """
    Normalizes any dataframe into a standard schema:
    [id, input_text, human_label]
    """
    # 1. Flatten if necessary (for nested json/parquet cols like in SummHF)
    # Simple flatten for 'dot' notation columns if they don't exist
    for col in config.cols_text + [config.col_label, config.col_id]:
        if "." in col and col not in df.columns:
            # Very basic flattening support
            parts = col.split(".")
            if parts[0] in df.columns:
                df[col] = df[parts[0]].apply(lambda x: x.get(parts[1], {}) if isinstance(x, dict) else np.nan)
                if len(parts) > 2: # support deeper nesting like summary.axes.overall
                     df[col] = df[col].apply(lambda x: x.get(parts[2], np.nan) if isinstance(x, dict) else np.nan)

    # 2. Construct Input Text (Merge multiple columns)
    def merge_text(row):
        texts = []
        for c in config.cols_text:
            val = str(row.get(c, "")).strip()
            if val: texts.append(f"[{c.upper()}]:\n{val}")
        return "\n\n".join(texts)

    # 3. Create Standard DF
    out_df = pd.DataFrame()

    # Auto-detect ID if missing
    if config.col_id not in df.columns:
        out_df["id"] = range(len(df))
    else:
        out_df["id"] = df[config.col_id].astype(str)

    out_df["input_text"] = df.apply(merge_text, axis=1)

    # Handle Labels (Summation logic for DREsS handled here if 'total' missing)
    if config.col_label not in df.columns and config.name == "DRESS":
        # Fallback for DREsS if total column missing
        cols = ['content', 'organization', 'language']
        if all(c in df.columns for c in cols):
            out_df["human_label"] = df[cols].sum(axis=1)
    else:
        out_df["human_label"] = pd.to_numeric(df[config.col_label], errors='coerce')

    return out_df.dropna(subset=["input_text", "human_label"])

