# 4. Calibration & Metrics
# ==========================================

def run_calibration_and_predict(train_res: List[Dict], test_res: List[Dict], config: TaskConfig):
    # 1. Prepare Data
    X_train = [r['raw_pred'] for r in train_res if r['raw_pred'] != -1]
    y_train = [r['human'] for r in train_res if r['raw_pred'] != -1]

    if len(X_train) < 10:
        print("Warning: Not enough valid calibration data. Skipping calibration.")
        iso = None
    else:
        # 2. Fit Isotonic Regression
        iso = IsotonicRegression(y_min=config.min_score, y_max=config.max_score, out_of_bounds="clip")
        iso.fit(X_train, y_train)

    # 3. Predict & Round
    final_preds = []
    for r in test_res:
        val = r['raw_pred']
        if val == -1:
            final_preds.append(config.min_score)
            continue

        if iso:
            val = iso.predict([val])[0]

        # Universal Rounding Logic (Step Size)
        # e.g., if step=1 -> round(x); if step=0.5 -> round(x*2)/2
        val = round(val / config.step_size) * config.step_size
        final_preds.append(val)

    return final_preds

