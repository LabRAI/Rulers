# 3. Universal Scorer
# ==========================================

@dataclass
class UsageStats:
    prompt_tokens: int = 0
    completion_tokens: int = 0
    cost: float = 0.0
    lock: threading.Lock = threading.Lock()

    def update(self, pt, ct):
        with self.lock:
            self.prompt_tokens += pt
            self.completion_tokens += ct
            self.cost += (pt * 0.15 + ct * 0.60) / 1e6

def call_llm(model, messages, api_key, max_tokens=200):
    from openai import OpenAI
    client = OpenAI(api_key=api_key)
    try:
        resp = client.chat.completions.create(
            model=model, messages=messages, max_tokens=max_tokens, temperature=0.0,
            response_format={"type": "json_object"}
        )
        return resp.choices[0].message.content, resp.usage.prompt_tokens, resp.usage.completion_tokens
    except Exception as e:
        print(f"LLM Error: {e}")
        return "{}", 0, 0

def score_single_row(row, config: TaskConfig, model_name: str, api_key: str, usage: UsageStats):
    prompt = f"""
[Rubric]
{config.rubric_text}

[Input Data]
{row['input_text'][:12000]}

[Task]
Evaluate the Input Data based on the Rubric.
Assign a score between {config.min_score} and {config.max_score}.
Output strict JSON: {{"score": <number>, "reason": "<short justification>"}}
"""
    msgs = [{"role": "system", "content": "You are an expert evaluator."}, {"role": "user", "content": prompt}]

    txt, pt, ct = call_llm(model_name, msgs, api_key)
    usage.update(pt, ct)

    try:
        data = json.loads(txt)
        raw = float(data.get("score", -1))
    except:
        raw = -1.0

    # Clamp
    if raw != -1:
        raw = max(config.min_score, min(config.max_score, raw))

    return {
        "id": row['id'],
        "human": row['human_label'],
        "raw_pred": raw,
        "response": txt
    }

