"""
Universal DHS (Direct Holistic Scoring) Baseline
------------------------------------------------
A completely generalized pipeline for LLM-as-a-Judge tasks.
This script normalizes any text scoring task into a standard flow:
   Input(Text) + Rubric -> LLM -> Raw Score -> Calibration -> Final Score

Features:
- Dataset Agnostic: Handles any CSV/TSV/Parquet via column mapping.
- Logic Agnostic: No dataset-specific branches in the main loop.
- Input Fusion: Automatically merges 'Prompt' and 'Response' columns if needed.
- Configurable: Score ranges, step sizes (int vs float), and rubrics are parameters.

Usage:
  python run_dhs_universal.py --preset ASAP --openai_key "..."
  python run_dhs_universal.py --data_path data.csv --rubric_path r.txt --min_score 1 --max_score 5
"""

