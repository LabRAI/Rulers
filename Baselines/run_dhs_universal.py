def main():
    parser = argparse.ArgumentParser(description="Universal DHS Runner")
    # Configuration sources
    parser.add_argument("--preset", choices=PRESETS.keys(), help="Load defaults for specific dataset")
    parser.add_argument("--rubric_path", help="Path to rubric text file (overrides preset)")
    parser.add_argument("--rubric_text", help="Inline rubric text (overrides preset)")

    # Data Paths
    parser.add_argument("--data_path", required=True, help="Main data file (train or full)")
    parser.add_argument("--test_path", help="Optional separate test file")

    # Generic Config Overrides (make it truly universal)
    parser.add_argument("--min_score", type=float)
    parser.add_argument("--max_score", type=float)
    parser.add_argument("--step_size", type=float, default=1.0)
    parser.add_argument("--cols_text", help="Comma-separated list of text columns")
    parser.add_argument("--col_label", help="Label column name")
    parser.add_argument("--col_id", help="ID column name")

    # Runtime
    parser.add_argument("--openai_key", default=os.getenv("OPENAI_API_KEY"))
    parser.add_argument("--model", default="gpt-4o-mini")
    parser.add_argument("--calib_n", type=int, default=100)
    parser.add_argument("--max_test", type=int, default=500)
    parser.add_argument("--parallel", type=int, default=8)
    parser.add_argument("--out_dir", default="results_universal")

    args = parser.parse_args()

    # 1. Build Configuration Object
    if args.preset:
        cfg = PRESETS[args.preset]
    else:
        # Default fallback config
        cfg = TaskConfig("CUSTOM", "", 1, 5, 1, ["text"], "label", "id")

    # Override config with explicit args if provided
    if args.min_score: cfg.min_score = args.min_score
    if args.max_score: cfg.max_score = args.max_score
    if args.step_size: cfg.step_size = args.step_size
    if args.cols_text: cfg.cols_text = args.cols_text.split(",")
    if args.col_label: cfg.col_label = args.col_label
    if args.col_id: cfg.col_id = args.col_id

    # Load Rubric Text
    if args.rubric_path:
        with open(args.rubric_path, 'r', encoding='utf-8') as f: cfg.rubric_text = f.read()
    elif args.rubric_text:
        cfg.rubric_text = args.rubric_text

    print(f"--- Universal Run: {cfg.name} ---")
    print(f"Range: [{cfg.min_score}, {cfg.max_score}], Step: {cfg.step_size}")
    print(f"Input Cols: {cfg.cols_text} -> Merged")

    # 2. Load Data
    full_df = smart_load(args.data_path)
    full_std = normalize_data(full_df, cfg)

    if args.test_path:
        test_df_raw = smart_load(args.test_path)
        test_std = normalize_data(test_df_raw, cfg)
        train_std = full_std # Use data_path as train
    else:
        # Split single file
        train_std = full_std.iloc[:args.calib_n]
        test_std = full_std.iloc[args.calib_n:]

    # Subsample
    train_std = train_std.head(args.calib_n)
    test_std = test_std.head(args.max_test)

    print(f"Train N: {len(train_std)}, Test N: {len(test_std)}")
    os.makedirs(args.out_dir, exist_ok=True)
    usage = UsageStats()

    # 3. Execution Engine (Generic Loop)
    def run_batch(df, desc):
        results = []
        with ThreadPoolExecutor(max_workers=args.parallel) as ex:
            futs = [ex.submit(score_single_row, row, cfg, args.model, args.openai_key, usage) for _, row in df.iterrows()]
            for f in as_completed(futs):
                results.append(f.result())
            print(f"Finished {desc}")
        return results

    # Run Calibration Phase
    calib_res = run_batch(train_std, "Calibration Phase")

    # Run Test Phase
    test_res = run_batch(test_std, "Test Phase")

    # 4. Calibration & Prediction
    final_preds = run_calibration_and_predict(calib_res, test_res, cfg)

    # 5. Metrics & Saving
    y_true = [r['human'] for r in test_res]

    # QWK Handling: Map floats to integers via step size for QWK calculation
    # e.g. for step 0.5: 3.0->6, 3.5->7. This preserves ordinality perfectly.
    factor = int(1 / cfg.step_size)
    yt_int = np.round(np.array(y_true) * factor).astype(int)
    yp_int = np.round(np.array(final_preds) * factor).astype(int)

    qwk = cohen_kappa_score(yt_int, yp_int, weights="quadratic")

    # Save output
    out_df = pd.DataFrame(test_res)
    out_df['final_pred'] = final_preds
    out_df.to_csv(os.path.join(args.out_dir, "predictions.csv"), index=False)

    print("\n" + "="*40)
    print(f"RESULTS ({cfg.name})")
    print(f"QWK Score: {qwk:.4f}")
    print(f"Est. Cost: ${usage.cost:.4f}")
    print("="*40)

if __name__ == "__main__":
    main()