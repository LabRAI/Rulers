def get_client(api_key: str):
    return OpenAI(api_key=api_key)

def calculate_hash(data: Any) -> str:
    s = json.dumps(data, sort_keys=True, ensure_ascii=False)
    return hashlib.sha256(s.encode('utf-8')).hexdigest()[:16]

def split_sentences(text: str) -> List[Dict[str, Any]]:
    # For summarization, usually involves source and summary.
    # Here we simplify to just the summary text for the "Sentence Bank" structure
    raw_sents = [s.strip() for s in text.replace('\n', '.').split('.') if s.strip()]
    return [{"sent_id": i, "text": s} for i, s in enumerate(raw_sents)]

